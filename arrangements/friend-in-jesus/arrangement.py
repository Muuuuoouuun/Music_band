def phrase_bars(name: str, nxt: str | None):
    if name == "a":
        return phrase_a(PICKUP_AB)
    if name == "c":
        return phrase_c()
    return phrase_b(END_TO_C if nxt == "c" else END_HOLD if nxt is None else
                    [(2, "F4", "A4", "C4"), (1, R, R, R), (.5, R, R, R)] + PICKUP_AB)


def eighths(bars):
    """마디 목록 -> 8분음표 칸마다 (멜로디, 윗, 아래) MIDI 번호 (쉼 = None). 첫 음은 시작 여부 표시."""
    from music21 import pitch

    def midi(p):
        return None if p == R else pitch.Pitch(p.rstrip("~")).midi

    out = []
    for b in bars:
        for d, *ps in b["notes"]:
            vals = tuple(midi(p) for p in ps)
            for k in range(int(round(d * 2))):
                out.append(vals)
    return out
