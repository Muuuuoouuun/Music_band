"""내 진정 사모하는 (찬송가 88장, F.I.A LIVE WORSHIP 버전) — 멜로디·화성·곡 구조 데이터.

악보(build.py)와 화음 음원(render_audio.py)이 같은 데이터를 쓴다.

- 멜로디는 영상 음원에서 메인 보컬만 분리(Mel-RoFormer Karaoke)한 뒤 CREPE 음높이를 8분음표 격자로 모으고,
  같은 프레이즈가 나오는 4~6번을 겹쳐 다수결로 정했다. 적은 음높이는 '악보 표기 음높이'다
  (영상의 남성 인도자는 한 옥타브 아래로 부른다).
- 화성(윗화음 High · 아랫화음 Low)은 원곡에 없는 새 편곡이다. 원곡 코러스는 대부분 멜로디를 옥타브 위로 겹쳐 부른다.
- 가사는 넣지 않았다. 리듬은 멜로디와 같다(호모포니).
"""
from __future__ import annotations

BPM = 103  # 영상 실측 103~104
KEY_FIFTHS = -1  # F장조
R = "r"

# 음 하나 = (길이(4분음표=1), 멜로디, 윗화음, 아랫화음). 음 이름 끝 "~" 는 다음 음과 붙임줄.
# 마디 = dict(notes=[...], chords=[(박 위치, 코드)])

# 다음 프레이즈로 들어가는 못갖춘 음 (마디 4번째 박 근처)
PICKUP_AB = [(.5, "A4", "C5", "F4"), (.5, "Bb4", "D5", "G4"), (.5, "C5", "F5", "A4")]  # 3박 반부터
PICKUP_C = [(.5, "F4", "A4", "C4"), (.5, "Bb4", "D5", "F4")]  # 4박부터


def bar(notes, chords):
    assert abs(sum(n[0] for n in notes) - 4) < 1e-6, notes
    return dict(notes=notes, chords=chords)


# 절·후렴에 공통인 앞 두 마디
BAR1 = [(.5, "C5", "F5", "A4"), (.5, "D5", "F5", "Bb4"), (.5, "C5", "F5", "A4"), (.5, "C5", "F5", "A4"),
        (1, "A4", "C5", "F4"), (.5, "F4", "A4", "D4"), (.5, "G4", "Bb4", "E4")]
BAR2 = [(.5, "F4", "Bb4", "D4"), (.5, "F4", "Bb4", "D4"), (.5, "D4", "F4", "Bb3"), (1, R, R, R),
        (.5, "F4", "A4", "C4"), (.5, "G4", "Bb4", "E4"), (.5, "A4", "C5", "F4")]


def phrase_a(pickup):
    """절 앞 4마디."""
    return [
        bar(BAR1, [(0, "F")]),
        bar(BAR2, [(0, "Bb"), (2, "F/C")]),
        bar([(.5, "A4", "C5", "F4"), (.5, "A4", "C5", "F4"), (.5, "A4", "C5", "F4"), (.5, "D5", "F5", "Bb4"),
             (.5, "C5", "F5", "A4"), (.5, "C5", "F5", "A4"), (1, "G4~", "Bb4~", "D4~")], [(0, "F")]),
        bar([(1, "G4", "Bb4", "D4"), (1, R, R, R), (.5, R, R, R)] + pickup, [(0, "Bb"), (2, "Csus4")]),
    ]


def phrase_b(last):
    """절·후렴 뒤 4마디 (끝이 F 로 닫힘). last = 마지막 마디의 음."""
    return [
        bar(BAR1, [(0, "F")]),
        bar(BAR2, [(0, "Bb"), (2, "Csus4")]),
        bar([(.5, "C5", "F5", "F4"), (.5, "A4", "D5", "F4"), (.5, "F4", "Bb4", "D4"), (.5, "G4", "Bb4", "D4"),
             (.5, "A4", "C5", "E4"), (.5, "A4", "C5", "E4"), (.5, "G4", "C5", "E4"), (.5, "F4", "C5", "C4")],
            [(0, "Bb"), (2, "C")]),
        bar(last, [(0, "F")]),
    ]


def phrase_c():
    """후렴 앞 4마디 (B♭ – D 로 높게 시작)."""
    return [
        bar([(.5, "Bb4", "D5", "F4")] * 4 + [(1, "D5", "F5", "Bb4"), (.5, "D5", "F5", "Bb4"), (.5, "D5", "F5", "Bb4")],
            [(0, "Bb")]),
        bar([(.5, "C5", "F5", "A4"), (.5, "C5", "F5", "A4"), (.5, "A4", "D5", "F4"), (1, "C5", "F5", "A4"),
             (.5, "A4", "C5", "F4"), (.5, "G4", "Bb4", "E4"), (.5, "F4", "A4", "D4")], [(0, "Dm")]),
        bar([(1.5, "F4", "B4", "D4"), (.5, "D5", "F5", "B4"), (.5, "C5", "E5", "G4"), (.5, "C5", "E5", "G4"),
             (1, "G4~", "C5~", "E4~")], [(0, "G7"), (2, "C")]),
        bar([(1, "G4", "C5", "E4"), (1, R, R, R), (.5, R, R, R)] + PICKUP_AB, [(0, "C"), (2, "Bb/C")]),
    ]


END_TO_C = [(2, "F4", "A4", "C4"), (1, R, R, R)] + PICKUP_C  # 다음이 후렴
END_HOLD = [(2, "F4", "A4", "C4"), (2, R, R, R)]  # 간주·끝

VERSE = phrase_a(PICKUP_AB) + phrase_b(END_TO_C)  # 8마디
REFRAIN = phrase_c() + phrase_b(END_HOLD)  # 8마디 (악보에서는 끝 마디를 1·2번 괄호로 나눔)

